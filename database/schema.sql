-- CodeAI adaptive learning: PostgreSQL schema (Amazon Aurora Serverless v2, PostgreSQL-compatible)
-- Mirrors database/data-model.mmd (table and column names are identical).
--
-- Conventions
--   * Identifiers are unquoted, so PostgreSQL folds them to lower case
--     (StudentId is stored as studentid). Query with any case, but expect
--     lower-case column names in result sets.
--   * Datetimes are TIMESTAMPTZ and are stored and returned in UTC.
--   * JSON columns (CheckSpec, Payload, EvidenceMap, EvidenceRefs) are JSONB.
--   * Scores and thresholds (McqScore, ThresholdInMCQ) are percentages, 0 to 100.
--   * Master data uses integer ids. Course structure (CHECKPOINT, STEP) uses the
--     string slugs from sample-skilltree.json as primary keys (C-5).
--   * Student-state tables match the contract records in
--     shared/contracts/schemas/records.schema.json (Task 4.6, ADR-017):
--       - student and teacher ids are strings (e.g. 'stu-quick'), not integers;
--       - skills are referenced by their slug (SKILLS.Slug, e.g. 'build');
--       - every column name is the record key in lower case, so the store
--         adapter maps a result column to a record key by lower-casing the key
--         (studentId -> studentid). Surrogate ids the contract does not carry
--         (EvidenceId, FlagId, FallbackEventId) are internal and never returned;
--       - evidence levels are the per-skill rubric levels 0..3 (C-9). The 0..4
--         competence scale applies only to the master-data STUDENT table.
--   * Integer ids are IDENTITY columns (GENERATED BY DEFAULT), so seed.sql can
--     insert fixed ids. seed.sql resets the sequences afterwards.
--   * Re-running this file rebuilds the schema from scratch and drops all data.
--     Never run it against a database that holds real student data.

BEGIN;

-- Drop in dependency order (children first).
DROP TABLE IF EXISTS TEACHER_INPUT CASCADE;
DROP TABLE IF EXISTS HINT_EVENT CASCADE;
DROP TABLE IF EXISTS PASSIVE_SIGNAL CASCADE;
DROP TABLE IF EXISTS FALLBACK_EVENT CASCADE;
DROP TABLE IF EXISTS ROUTING_DECISION CASCADE;
DROP TABLE IF EXISTS REMEDIATION_FLAG CASCADE;
DROP TABLE IF EXISTS CHECKPOINT_PROGRESS CASCADE;
DROP TABLE IF EXISTS STEP_ATTEMPT CASCADE;
DROP TABLE IF EXISTS STUDENT_SKILL_EVIDENCE CASCADE;
DROP TABLE IF EXISTS TEACHER_CONFIG CASCADE;
DROP TABLE IF EXISTS TEACHER CASCADE;
DROP TABLE IF EXISTS STUDENT CASCADE;
DROP TABLE IF EXISTS STUDENT_ENROLLED_COURSES CASCADE;
DROP TABLE IF EXISTS STUDENT_PROFILE CASCADE;
DROP TABLE IF EXISTS MEASURE CASCADE;
DROP TABLE IF EXISTS STEP CASCADE;
DROP TABLE IF EXISTS CHECKPOINT_TARGET CASCADE;
DROP TABLE IF EXISTS CHECKPOINT_REQUIRES CASCADE;
DROP TABLE IF EXISTS CHECKPOINT CASCADE;
DROP TABLE IF EXISTS LEARNING_EXAMPLES CASCADE;
DROP TABLE IF EXISTS MCQ_QUESTIONS CASCADE;
DROP TABLE IF EXISTS SKILL_LEVEL_DESCRIPTOR CASCADE;
DROP TABLE IF EXISTS SKILL_RUBRIC_CRITERIA CASCADE;
DROP TABLE IF EXISTS SKILL_TIER_CONTENT CASCADE;
DROP TABLE IF EXISTS SKILLS CASCADE;
DROP TABLE IF EXISTS COMPETENCE_LEVELS_MASTER CASCADE;
DROP TABLE IF EXISTS COURSE CASCADE;

-- ---------------------------------------------------------------------------
-- Master data: course and skills
-- ---------------------------------------------------------------------------

CREATE TABLE COURSE (
    CourseId     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CourseTitle  TEXT NOT NULL
);

CREATE TABLE SKILLS (
    SkillId          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CourseId         INTEGER NOT NULL REFERENCES COURSE (CourseId) ON DELETE CASCADE,
    -- Stable string id (C-5). Student-state tables reference skills by this slug.
    Slug             TEXT NOT NULL UNIQUE CHECK (Slug ~ '^[a-z0-9][a-z0-9-]*$'),
    Title            TEXT NOT NULL,
    Description      TEXT,
    LessonObjective  TEXT
);

CREATE INDEX idx_skills_course ON SKILLS (CourseId);

-- Lookup: 0 None, 1 Beginner, 2 Competent, 3 Expert, 4 Master.
-- ThresholdInMCQ is the minimum MCQ score (percent) needed to reach the level.
CREATE TABLE COMPETENCE_LEVELS_MASTER (
    LevelId         INTEGER PRIMARY KEY CHECK (LevelId BETWEEN 0 AND 4),
    LevelName       TEXT NOT NULL UNIQUE,
    Rubric          TEXT,
    ThresholdInMCQ  INTEGER NOT NULL CHECK (ThresholdInMCQ BETWEEN 0 AND 100)
);

-- ---------------------------------------------------------------------------
-- Master data: assessment and teaching material, all hanging off a skill
-- ---------------------------------------------------------------------------

-- PossibleAnswers is comma-separated, so answer text must not contain commas.
-- CorrectAnswer is the exact text of one of the possible answers.
CREATE TABLE MCQ_QUESTIONS (
    QuestionId       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SkillId          INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    MCQQuestion      TEXT NOT NULL,
    PossibleAnswers  TEXT NOT NULL,
    CorrectAnswer    TEXT NOT NULL
);

CREATE INDEX idx_mcq_skill ON MCQ_QUESTIONS (SkillId);

-- Example holds an HTML document or snippet. Several examples per skill are allowed.
CREATE TABLE LEARNING_EXAMPLES (
    ExampleId  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SkillId    INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    Example    TEXT NOT NULL
);

CREATE INDEX idx_examples_skill ON LEARNING_EXAMPLES (SkillId);

-- The practice task delivered for a skill, one row per tier:
--   core    default task every student sees
--   support scaffolded task for students who need more practice
--   depth   goes deeper on the same objective (never advances to new content)
-- Hints is numbered text, e.g. '1) first hint 2) second hint'.
CREATE TABLE SKILL_TIER_CONTENT (
    TierContentId  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SkillId        INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    Tier           TEXT NOT NULL CHECK (Tier IN ('core', 'support', 'depth')),
    Title          TEXT NOT NULL,
    Instructions   TEXT NOT NULL,
    StarterCode    TEXT,
    Hints          TEXT,
    UNIQUE (SkillId, Tier)
);

-- Weighted checks that score a submission for a skill. The weights of one
-- skill sum to 1, so submission score = sum of Weight over criteria that pass.
-- Method: dom = deterministic check on the parsed page, llm = judged check.
-- CheckSpec is a JSON document describing the check.
CREATE TABLE SKILL_RUBRIC_CRITERIA (
    CriterionId  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SkillId      INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    Description  TEXT NOT NULL,
    Weight       NUMERIC(4, 3) NOT NULL CHECK (Weight > 0 AND Weight <= 1),
    Method       TEXT NOT NULL CHECK (Method IN ('dom', 'llm')),
    CheckSpec    JSONB
);

CREATE INDEX idx_criteria_skill ON SKILL_RUBRIC_CRITERIA (SkillId);

-- What each competence level looks like for one skill.
CREATE TABLE SKILL_LEVEL_DESCRIPTOR (
    SkillId     INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    LevelId     INTEGER NOT NULL REFERENCES COMPETENCE_LEVELS_MASTER (LevelId),
    Descriptor  TEXT NOT NULL,
    PRIMARY KEY (SkillId, LevelId)
);

-- ---------------------------------------------------------------------------
-- Master data: course structure (checkpoints and steps)
-- Ids are the string slugs from database/sample-skilltree.json (C-5).
-- ---------------------------------------------------------------------------

CREATE TABLE CHECKPOINT (
    CheckpointId          TEXT PRIMARY KEY,
    CourseId              INTEGER NOT NULL REFERENCES COURSE (CourseId) ON DELETE CASCADE,
    Title                 TEXT NOT NULL,
    Description           TEXT,
    Destination           TEXT,
    Skippable             BOOLEAN NOT NULL DEFAULT FALSE,
    RouteAfterCompletion  BOOLEAN NOT NULL DEFAULT FALSE,
    -- JSON order. The linear fallback path follows it (C-21).
    Sequence              INTEGER NOT NULL,
    UNIQUE (CourseId, Sequence)
);

CREATE INDEX idx_checkpoint_course ON CHECKPOINT (CourseId);

-- A checkpoint is available when every row here is completed or tested out.
CREATE TABLE CHECKPOINT_REQUIRES (
    CheckpointId          TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId) ON DELETE CASCADE,
    RequiresCheckpointId  TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId) ON DELETE CASCADE,
    PRIMARY KEY (CheckpointId, RequiresCheckpointId),
    CHECK (CheckpointId <> RequiresCheckpointId)
);

CREATE INDEX idx_requires_prereq ON CHECKPOINT_REQUIRES (RequiresCheckpointId);

-- The evidence level a checkpoint expects for a skill. Defaults to 1 (C-12).
CREATE TABLE CHECKPOINT_TARGET (
    CheckpointId         TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId) ON DELETE CASCADE,
    SkillId              INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    TargetEvidenceLevel  INTEGER NOT NULL DEFAULT 1 CHECK (TargetEvidenceLevel BETWEEN 0 AND 3),
    PRIMARY KEY (CheckpointId, SkillId)
);

CREATE INDEX idx_target_skill ON CHECKPOINT_TARGET (SkillId);

-- Kind: panels (read only), level (widget or project task), questions.
-- Payload holds the kind-specific content (panels, questions, level reference).
-- ValidationCondition and ValidationSkillId are set only for project steps that
-- spell them out. Otherwise the validator derives them at runtime (architecture 2.5).
CREATE TABLE STEP (
    StepId              TEXT PRIMARY KEY,
    CheckpointId        TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId) ON DELETE CASCADE,
    Sequence            INTEGER NOT NULL,
    Kind                TEXT NOT NULL CHECK (Kind IN ('panels', 'level', 'questions')),
    Title               TEXT NOT NULL,
    IsProject           BOOLEAN NOT NULL DEFAULT FALSE,
    Instructions        TEXT,
    InstructionsPrompt  TEXT,
    Payload             JSONB,
    ValidationCondition TEXT,
    ValidationSkillId   INTEGER REFERENCES SKILLS (SkillId),
    UNIQUE (CheckpointId, Sequence)
);

CREATE INDEX idx_step_checkpoint ON STEP (CheckpointId);

-- Scores a multiple-choice question: EvidenceMap maps each choice to an
-- evidence level, for example {"a": 1, "b": 2}. No model call is needed (C-13).
CREATE TABLE MEASURE (
    MeasureId     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StepId        TEXT NOT NULL REFERENCES STEP (StepId) ON DELETE CASCADE,
    SkillId       INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    QuestionName  TEXT,
    EvidenceMap   JSONB NOT NULL
);

CREATE INDEX idx_measure_step ON MEASURE (StepId);
CREATE INDEX idx_measure_skill ON MEASURE (SkillId);

-- ---------------------------------------------------------------------------
-- Students and teachers
-- ---------------------------------------------------------------------------

-- Contract record: Student. Synthetic marks demo personas; the UI labels them (architecture 2.7).
CREATE TABLE STUDENT_PROFILE (
    StudentId    TEXT PRIMARY KEY CHECK (StudentId ~ '^[A-Za-z0-9_-]{1,64}$'),
    DisplayName  TEXT NOT NULL CHECK (char_length(DisplayName) BETWEEN 1 AND 80),
    Synthetic    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE STUDENT_ENROLLED_COURSES (
    StudentId  TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    CourseId   INTEGER NOT NULL REFERENCES COURSE (CourseId) ON DELETE CASCADE,
    PRIMARY KEY (StudentId, CourseId)
);

-- Per-student, per-skill progress. No row for a skill means not started,
-- which is equivalent to CompetenceLevel 0 (None).
CREATE TABLE STUDENT (
    StudentId        TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    SkillId          INTEGER NOT NULL REFERENCES SKILLS (SkillId) ON DELETE CASCADE,
    CompetenceLevel  INTEGER NOT NULL REFERENCES COMPETENCE_LEVELS_MASTER (LevelId),
    McqScore         INTEGER NOT NULL CHECK (McqScore BETWEEN 0 AND 100),
    CreatedAt        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UpdatedAt        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (StudentId, SkillId)
);

CREATE INDEX idx_student_skill ON STUDENT (SkillId);

CREATE TABLE TEACHER (
    TeacherId    TEXT PRIMARY KEY CHECK (TeacherId ~ '^[A-Za-z0-9_-]{1,64}$'),
    DisplayName  TEXT NOT NULL
);

CREATE TABLE TEACHER_CONFIG (
    TeacherId            TEXT PRIMARY KEY REFERENCES TEACHER (TeacherId) ON DELETE CASCADE,
    AnswerTimeoutSeconds INTEGER NOT NULL DEFAULT 180 CHECK (AnswerTimeoutSeconds BETWEEN 10 AND 3600)
);

-- ---------------------------------------------------------------------------
-- Transactional state (architecture 2.9)
-- Student work contains minors' text. Restrict access and encrypt at rest
-- (Aurora storage encryption with a KMS key).
-- ---------------------------------------------------------------------------

-- Append-only. A student's skill level is the max Level observed (C-10).
CREATE TABLE STUDENT_SKILL_EVIDENCE (
    EvidenceId    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StudentId     TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    SkillId       TEXT NOT NULL REFERENCES SKILLS (Slug) ON DELETE CASCADE,
    -- 0..3; the per-skill maximum (build 2, language 3, debug 3) is checked at runtime (C-9).
    Level         INTEGER NOT NULL CHECK (Level BETWEEN 0 AND 3),
    SourceStepId  TEXT NOT NULL REFERENCES STEP (StepId),
    CreatedAt     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_evidence_student_skill ON STUDENT_SKILL_EVIDENCE (StudentId, SkillId);

-- One row per submit.
CREATE TABLE STEP_ATTEMPT (
    AttemptId           TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    StudentId           TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    StepId              TEXT NOT NULL REFERENCES STEP (StepId),
    InputText           TEXT CHECK (char_length(InputText) <= 4000),
    ProjectSnapshotRef  TEXT CHECK (char_length(ProjectSnapshotRef) <= 200),
    EvidenceLevel       INTEGER CHECK (EvidenceLevel BETWEEN 0 AND 3),
    Confidence          DOUBLE PRECISION CHECK (Confidence BETWEEN 0 AND 1),
    -- Not in the contract record. Optional audit field for the validator prompt hash (architecture 2.10).
    PromptVersion       TEXT,
    CreatedAt           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_attempt_student_time ON STEP_ATTEMPT (StudentId, CreatedAt);
CREATE INDEX idx_attempt_step ON STEP_ATTEMPT (StepId);

-- Status moves locked -> available -> current -> completed. tested_out is set
-- for skippable checkpoints whose target the diagnostic already met.
-- Completion reverses only on a teacher reset (C-12).
CREATE TABLE CHECKPOINT_PROGRESS (
    StudentId     TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    CheckpointId  TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId),
    Status        TEXT NOT NULL CHECK (Status IN ('locked', 'available', 'current', 'completed', 'tested_out')),
    UpdatedAt     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (StudentId, CheckpointId)
);

-- Two consecutive misses on a skill create one. Severity 'high' after four.
CREATE TABLE REMEDIATION_FLAG (
    FlagId      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StudentId   TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    SkillId     TEXT NOT NULL REFERENCES SKILLS (Slug) ON DELETE CASCADE,
    Reason      TEXT NOT NULL,
    Severity    TEXT NOT NULL DEFAULT 'normal' CHECK (Severity IN ('normal', 'high')),
    CreatedAt   TIMESTAMPTZ NOT NULL DEFAULT now(),
    ResolvedAt  TIMESTAMPTZ
);

-- Feeds the teacher roster: open flags, most severe first.
CREATE INDEX idx_flag_open ON REMEDIATION_FLAG (Severity, StudentId) WHERE ResolvedAt IS NULL;

-- Written on every route call, with a readable reason (C-19.5).
-- TeacherInput is a snapshot of the teacher input the route call saw, the contract
-- TeacherInput object: {"mode": "auto" | "hold" | "assign", "checkpointId"?: slug}.
-- The standing hold or assign lives in TEACHER_INPUT.
CREATE TABLE ROUTING_DECISION (
    DecisionId            TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    StudentId             TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    ProposedCheckpointId  TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId),
    TeacherInput          JSONB NOT NULL DEFAULT '{"mode": "auto"}'
                          CHECK (TeacherInput->>'mode' IN ('auto', 'hold', 'assign')
                                 AND (TeacherInput->>'mode' <> 'assign' OR TeacherInput ? 'checkpointId')),
    AppliedCheckpointId   TEXT NOT NULL REFERENCES CHECKPOINT (CheckpointId),
    Reason                TEXT NOT NULL,
    CreatedAt             TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_routing_student_time ON ROUTING_DECISION (StudentId, CreatedAt);

CREATE TABLE FALLBACK_EVENT (
    FallbackEventId  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StudentId        TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    StepId           TEXT REFERENCES STEP (StepId),
    Component        TEXT NOT NULL CHECK (Component IN ('validation', 'routing', 'generation', 'safety', 'passive')),
    -- A code or short reason. Never student text.
    Error            TEXT NOT NULL CHECK (char_length(Error) BETWEEN 1 AND 400),
    CreatedAt        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_fallback_student_time ON FALLBACK_EVENT (StudentId, CreatedAt);

-- Passive evaluator output. ModelId is 'rules' when the rule-based fallback produced it.
CREATE TABLE PASSIVE_SIGNAL (
    SignalId       TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    StudentId      TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    Signal         TEXT NOT NULL CHECK (Signal IN ('speed_up', 'slow_down', 'redirect', 'reengage', 'steady')),
    HintStyle      TEXT NOT NULL CHECK (HintStyle IN ('guiding_question', 'example', 'analogy', 'step_by_step')),
    AngleToTry     TEXT CHECK (char_length(AngleToTry) <= 120),
    Reason         TEXT NOT NULL,
    EvidenceRefs   JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(EvidenceRefs) = 'array'),
    Confidence     DOUBLE PRECISION NOT NULL CHECK (Confidence BETWEEN 0 AND 1),
    FeaturesHash   TEXT NOT NULL CHECK (FeaturesHash ~ '^[a-f0-9]{8,64}$'),
    ModelId        TEXT NOT NULL,
    PromptVersion  TEXT NOT NULL,
    CreatedAt      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_signal_student_time ON PASSIVE_SIGNAL (StudentId, CreatedAt);
-- Cache lookup: features_hash + prompt_version.
CREATE INDEX idx_signal_cache ON PASSIVE_SIGNAL (FeaturesHash, PromptVersion);

-- Hint log. Passive reads it to avoid repeating an explanation angle.
CREATE TABLE HINT_EVENT (
    HintId     TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    StudentId  TEXT NOT NULL REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    StepId     TEXT NOT NULL REFERENCES STEP (StepId),
    Style      TEXT NOT NULL CHECK (Style IN ('guiding_question', 'example', 'analogy', 'step_by_step')),
    Angle      TEXT CHECK (char_length(Angle) <= 120),
    CreatedAt  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_hint_student_time ON HINT_EVENT (StudentId, CreatedAt);

-- The standing teacher hold or assign for a student (C-19.4). It persists until the
-- teacher changes it. No row means mode 'auto'. Each route call snapshots it into
-- ROUTING_DECISION.TeacherInput.
CREATE TABLE TEACHER_INPUT (
    StudentId     TEXT PRIMARY KEY REFERENCES STUDENT_PROFILE (StudentId) ON DELETE CASCADE,
    Mode          TEXT NOT NULL CHECK (Mode IN ('auto', 'hold', 'assign')),
    CheckpointId  TEXT REFERENCES CHECKPOINT (CheckpointId),
    UpdatedAt     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (Mode <> 'assign' OR CheckpointId IS NOT NULL)
);

COMMIT;
